import AppKit
import Foundation

// MARK: - ClipboardClassifier
// Inspects an NSPasteboard and determines the best ClipboardType.
// Priority: image > richText > url > text > file > unknown.

enum ClipboardClassifier {

    static let imageExtensions: Set<String> = [
        "png", "jpg", "jpeg", "gif", "webp", "heic", "heif", "tiff", "tif", "bmp", "svg", "ico", "icns"
    ]

    static let imagePasteboardTypes: Set<NSPasteboard.PasteboardType> = [
        .tiff,
        .png,
        NSPasteboard.PasteboardType("public.jpeg"),
        NSPasteboard.PasteboardType("public.jpeg-2000"),
        NSPasteboard.PasteboardType("public.heic"),
        NSPasteboard.PasteboardType("public.heif"),
        NSPasteboard.PasteboardType("org.webmproject.webp"),
        NSPasteboard.PasteboardType("com.compuserve.gif"),
        NSPasteboard.PasteboardType("com.apple.pict"),
        NSPasteboard.PasteboardType("com.microsoft.bmp"),
        NSPasteboard.PasteboardType("com.apple.icns"),
        NSPasteboard.PasteboardType("public.image")
    ]

    static func classify(pasteboard: NSPasteboard) -> ClipboardType {
        let types = Set(pasteboard.types ?? [])

        // 1. Direct Image or Image File
        if !types.isDisjoint(with: imagePasteboardTypes) || NSImage.canInit(with: pasteboard) {
            if types.contains(.fileURL) {
                if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL],
                   let url = urls.first {
                    if imageExtensions.contains(url.pathExtension.lowercased()) {
                        return .image
                    } else {
                        return .file
                    }
                }
            }
            return .image
        }

        // 2. File URL (prioritized over plain text string so Finder copies are not treated as text)
        if types.contains(.fileURL) {
            if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL],
               let url = urls.first,
               imageExtensions.contains(url.pathExtension.lowercased()) {
                return .image
            }
            return .file
        }

        // 3. Rich text — RTF
        if types.contains(.rtf) || types.contains(NSPasteboard.PasteboardType("public.rtf")) {
            return .richText
        }

        // 4. URL — check string content
        if let string = pasteboard.string(forType: .string), isHTTPURL(string) {
            return .url
        }

        // 5. Plain text
        if types.contains(.string) {
            return .text
        }

        return .unknown
    }

    // MARK: - Privacy & Concealment Detection
    
    /// Detects if the pasteboard item is marked as confidential or transient by password managers or secure field entries
    /// (1Password, Apple Passwords, Keychain, Bitwarden, KeePassXC, LastPass, Dashlane, etc.)
    static func isConcealed(pasteboard: NSPasteboard) -> Bool {
        guard let types = pasteboard.types else { return false }
        
        let concealedIdentifiers: Set<String> = [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.AutoGeneratedType",
            "org.nspasteboard.TransientType",
            "de.petermaurer.TransientPasteboardType",
            "com.agilebits.onepassword",
            "com.apple.Passwords",
            "com.apple.keychainaccess",
            "com.apple.SecurityAgent",
            "com.apple.findmy.security-transient",
            "com.bitwarden.desktop",
            "org.keepassxc.keepassxc",
            "com.lastpass.LastPass",
            "com.dashlane.dashlane",
            "in.sinew.Enpass-Desktop",
            "com.nordpass.macos",
            "com.typeit4me.clipping",
            "Pasteboard generator type",
            "net.sourceforge.macpass"
        ]
        
        for type in types {
            if concealedIdentifiers.contains(type.rawValue) {
                return true
            }
        }
        return false
    }

    /// Identifies whether an application bundle ID belongs to a known password manager or security entry
    static func isPasswordManagerBundleId(_ bundleId: String?) -> Bool {
        guard let id = bundleId?.lowercased() else { return false }
        let knownManagers: [String] = [
            "com.apple.passwords",
            "com.apple.keychainaccess",
            "com.apple.securityagent",
            "com.agilebits.onepassword",
            "com.1password",
            "com.bitwarden",
            "org.keepassxc",
            "com.lastpass",
            "com.dashlane",
            "in.sinew.enpass",
            "com.nordpass",
            "net.sourceforge.macpass",
            "com.msecure",
            "com.roboform",
            "com.stickypassword"
        ]
        return knownManagers.contains { id.contains($0) }
    }

    /// Determines if an item was copied from a secure field entry or password source
    static func isFieldEntryOrPassword(pasteboard: NSPasteboard, sourceApp: NSRunningApplication? = nil) -> Bool {
        if isConcealed(pasteboard: pasteboard) {
            return true
        }
        if isPasswordManagerBundleId(sourceApp?.bundleIdentifier) {
            return true
        }
        return false
    }

    // MARK: - Helpers

    static func isHTTPURL(_ string: String) -> Bool {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard let url = URL(string: trimmed) else { return false }
        return url.scheme == "http" || url.scheme == "https" || url.scheme == "ftp"
    }
}
